CREATE TRIGGER BI_EST_PARCELAS_CORTE FOR EST_PARCELAS_CORTE
ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.COD_EST_PARCELA_CORTE IS NULL) THEN
    NEW.COD_EST_PARCELA_CORTE = GEN_ID(GEN_EST_PARCELAS_CORTE, 1);
END^

CREATE TRIGGER BI_EST_EVENTOS_PARCELAS FOR EST_EVENTOS_PARCELAS
ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.COD_EST_EVENTO_PARCELA IS NULL) THEN
    NEW.COD_EST_EVENTO_PARCELA = GEN_ID(GEN_EST_EVENTOS_PARCELAS, 1);
END^

CREATE TRIGGER BI_EST_CARGAS_PARCELAS FOR EST_CARGAS_PARCELAS
ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.COD_EST_CARGA_PARCELA IS NULL) THEN
    NEW.COD_EST_CARGA_PARCELA = GEN_ID(GEN_EST_CARGAS_PARCELAS, 1);
END^

CREATE OR ALTER PROCEDURE REFRESCAR_ESTADISTICAS_PARCELAS (
  P_PERIODO DATE,
  P_FECHA_CORTE DATE,
  P_RECONSTRUIR SMALLINT)
AS
DECLARE VARIABLE V_PERIODO DATE;
DECLARE VARIABLE V_HASTA DATE;
DECLARE VARIABLE V_CANT_SNAPSHOTS INTEGER;
DECLARE VARIABLE V_CANT_EVENTOS INTEGER;
BEGIN
  IF (P_PERIODO IS NULL OR P_FECHA_CORTE IS NULL OR P_RECONSTRUIR IS NULL
      OR P_RECONSTRUIR NOT IN (0, 1)) THEN
    EXCEPTION EXC_ESTADISTICAS_PARCELAS;

  V_PERIODO = DATEADD(1 - EXTRACT(DAY FROM P_PERIODO) DAY TO P_PERIODO);
  V_HASTA = DATEADD(-1 DAY TO DATEADD(1 MONTH TO V_PERIODO));

  IF (P_FECHA_CORTE < V_PERIODO OR P_FECHA_CORTE > V_HASTA) THEN
    EXCEPTION EXC_ESTADISTICAS_PARCELAS;
  IF (P_RECONSTRUIR = 0 AND V_PERIODO <> DATEADD(1 - EXTRACT(DAY FROM CURRENT_DATE) DAY TO CURRENT_DATE)) THEN
    EXCEPTION EXC_ESTADISTICAS_PARCELAS;

  DELETE FROM EST_EVENTOS_PARCELAS WHERE PERIODO = :V_PERIODO;
  DELETE FROM EST_PARCELAS_CORTE WHERE PERIODO = :V_PERIODO;

  INSERT INTO EST_PARCELAS_CORTE (
    COD_PARCELA, COD_PROPUESTA, PERIODO, FECHA_CORTE, ES_ACTIVO, ES_AL_DIA,
    ES_MOROSO, ES_RECUPERADO, ES_DEUDOR_RECIENTE, MESES_PENDIENTES,
    TIENE_DPC, TIENE_FLORES_SIEMPRE, ACTUALIZADO_EN)
  SELECT P.COD_PARCELA, P.COD_PROPUESTA, :V_PERIODO, P_FECHA_CORTE,
    1,
    IIF(COALESCE((SELECT MAX(X.MESES) FROM (
      SELECT COUNT(*) AS MESES FROM CONFIG_CUOTAS_PERIODICAS CP
      INNER JOIN CUOTAS_PERIODICAS CU ON CU.COD_CONFIGURACION = CP.COD_CONFIGURACION
      WHERE CP.COD_PROPUESTA = P.COD_PROPUESTA AND (CP.FECHA_BAJA IS NULL OR CP.FECHA_BAJA > P_FECHA_CORTE)
        AND CU.FECHA_CUOTA <= P_FECHA_CORTE AND (CU.FECHA_RENDICION IS NULL OR CU.FECHA_RENDICION > P_FECHA_CORTE)
        AND CU.ANULADO = 0 AND CU.INACTIVO = 0
      UNION ALL
      SELECT COUNT(*) FROM CREDITOS CR INNER JOIN CUOTAS CU ON CU.COD_CREDITO = CR.COD_CREDITO
      WHERE CR.COD_PROPUESTA = P.COD_PROPUESTA AND (CR.FECHA_BAJA IS NULL OR CR.FECHA_BAJA > P_FECHA_CORTE)
        AND CU.FECHA_VENCIMIENTO <= P_FECHA_CORTE AND (CU.FECHA_RENDICION IS NULL OR CU.FECHA_RENDICION > P_FECHA_CORTE)
        AND CU.ANULADO = 0) X), 0) <= 2, 1, 0),
    IIF(COALESCE((SELECT MAX(X.MESES) FROM (
      SELECT COUNT(*) AS MESES FROM CONFIG_CUOTAS_PERIODICAS CP INNER JOIN CUOTAS_PERIODICAS CU ON CU.COD_CONFIGURACION = CP.COD_CONFIGURACION
      WHERE CP.COD_PROPUESTA = P.COD_PROPUESTA AND (CP.FECHA_BAJA IS NULL OR CP.FECHA_BAJA > P_FECHA_CORTE) AND CU.FECHA_CUOTA <= P_FECHA_CORTE AND (CU.FECHA_RENDICION IS NULL OR CU.FECHA_RENDICION > P_FECHA_CORTE) AND CU.ANULADO = 0 AND CU.INACTIVO = 0
      UNION ALL SELECT COUNT(*) FROM CREDITOS CR INNER JOIN CUOTAS CU ON CU.COD_CREDITO = CR.COD_CREDITO
      WHERE CR.COD_PROPUESTA = P.COD_PROPUESTA AND (CR.FECHA_BAJA IS NULL OR CR.FECHA_BAJA > P_FECHA_CORTE) AND CU.FECHA_VENCIMIENTO <= P_FECHA_CORTE AND (CU.FECHA_RENDICION IS NULL OR CU.FECHA_RENDICION > P_FECHA_CORTE) AND CU.ANULADO = 0) X), 0) >= 3, 1, 0),
    0, 0,
    COALESCE((SELECT MAX(X.MESES) FROM (
      SELECT COUNT(*) AS MESES FROM CONFIG_CUOTAS_PERIODICAS CP INNER JOIN CUOTAS_PERIODICAS CU ON CU.COD_CONFIGURACION = CP.COD_CONFIGURACION
      WHERE CP.COD_PROPUESTA = P.COD_PROPUESTA AND (CP.FECHA_BAJA IS NULL OR CP.FECHA_BAJA > P_FECHA_CORTE) AND CU.FECHA_CUOTA <= P_FECHA_CORTE AND (CU.FECHA_RENDICION IS NULL OR CU.FECHA_RENDICION > P_FECHA_CORTE) AND CU.ANULADO = 0 AND CU.INACTIVO = 0
      UNION ALL SELECT COUNT(*) FROM CREDITOS CR INNER JOIN CUOTAS CU ON CU.COD_CREDITO = CR.COD_CREDITO
      WHERE CR.COD_PROPUESTA = P.COD_PROPUESTA AND (CR.FECHA_BAJA IS NULL OR CR.FECHA_BAJA > P_FECHA_CORTE) AND CU.FECHA_VENCIMIENTO <= P_FECHA_CORTE AND (CU.FECHA_RENDICION IS NULL OR CU.FECHA_RENDICION > P_FECHA_CORTE) AND CU.ANULADO = 0) X), 0),
    IIF(EXISTS(SELECT 1 FROM CONFIG_CUOTAS_PERIODICAS C WHERE C.COD_PROPUESTA = P.COD_PROPUESTA AND C.COD_CAT_CUOTA_PERIODICA BETWEEN 11 AND 15 AND (C.FECHA_BAJA IS NULL OR C.FECHA_BAJA > P_FECHA_CORTE)), 1, 0),
    IIF(EXISTS(SELECT 1 FROM CONFIG_CUOTAS_PERIODICAS C INNER JOIN CAT_CUOTAS_PERIODICAS CT ON CT.COD_CAT_CUOTA_PERIODICA = C.COD_CAT_CUOTA_PERIODICA WHERE C.COD_PROPUESTA = P.COD_PROPUESTA AND CT.ES_FLORES_SIEMPRE = 1 AND (C.FECHA_BAJA IS NULL OR C.FECHA_BAJA > P_FECHA_CORTE)), 1, 0),
    CURRENT_TIMESTAMP
  FROM PROPUESTA P
  WHERE P.COD_PARCELA IS NOT NULL AND P.FECHA <= P_FECHA_CORTE AND (P.FECHA_BAJA IS NULL OR P.FECHA_BAJA > P_FECHA_CORTE)
    AND NOT EXISTS (SELECT 1 FROM PROPUESTA P2 WHERE P2.COD_PARCELA = P.COD_PARCELA AND P2.FECHA <= P_FECHA_CORTE AND (P2.FECHA_BAJA IS NULL OR P2.FECHA_BAJA > P_FECHA_CORTE) AND (P2.FECHA > P.FECHA OR (P2.FECHA = P.FECHA AND P2.COD_PROPUESTA > P.COD_PROPUESTA)));

  /* Recuperada: estaba morosa al iniciar el período y pagó una cuota hasta el corte durante el mes. */
  UPDATE EST_PARCELAS_CORTE E SET ES_RECUPERADO = 1
  WHERE E.PERIODO = :V_PERIODO AND E.ES_AL_DIA = 1
    AND EXISTS (SELECT 1 FROM CUOTAS_PERIODICAS CU INNER JOIN CONFIG_CUOTAS_PERIODICAS CP ON CP.COD_CONFIGURACION = CU.COD_CONFIGURACION WHERE CP.COD_PROPUESTA = E.COD_PROPUESTA AND CU.FECHA_CUOTA <= P_FECHA_CORTE AND CU.FECHA_RENDICION BETWEEN :V_PERIODO AND :P_FECHA_CORTE AND CU.ANULADO = 0 AND CU.INACTIVO = 0)
    AND (SELECT COUNT(*) FROM CUOTAS_PERIODICAS CU INNER JOIN CONFIG_CUOTAS_PERIODICAS CP ON CP.COD_CONFIGURACION = CU.COD_CONFIGURACION WHERE CP.COD_PROPUESTA = E.COD_PROPUESTA AND CU.FECHA_CUOTA < :V_PERIODO AND (CU.FECHA_RENDICION IS NULL OR CU.FECHA_RENDICION >= :V_PERIODO) AND CU.ANULADO = 0 AND CU.INACTIVO = 0) >= 3;

  INSERT INTO EST_EVENTOS_PARCELAS (COD_PARCELA, COD_PROPUESTA, PERIODO, FECHA_EVENTO, TIPO_EVENTO, MESES_PENDIENTES, ACTUALIZADO_EN)
  SELECT P.COD_PARCELA, P.COD_PROPUESTA, :V_PERIODO, P.FECHA, 'ALTA', NULL, CURRENT_TIMESTAMP FROM PROPUESTA P WHERE P.COD_PARCELA IS NOT NULL AND P.FECHA BETWEEN :V_PERIODO AND :V_HASTA;
  INSERT INTO EST_EVENTOS_PARCELAS (COD_PARCELA, COD_PROPUESTA, PERIODO, FECHA_EVENTO, TIPO_EVENTO, MESES_PENDIENTES, ACTUALIZADO_EN)
  SELECT P.COD_PARCELA, P.COD_PROPUESTA, :V_PERIODO, P.FECHA_BAJA, 'BAJA',
    (SELECT MAX(X.MESES) FROM (SELECT COUNT(*) AS MESES FROM CONFIG_CUOTAS_PERIODICAS CP INNER JOIN CUOTAS_PERIODICAS CU ON CU.COD_CONFIGURACION = CP.COD_CONFIGURACION WHERE CP.COD_PROPUESTA = P.COD_PROPUESTA AND CU.FECHA_CUOTA <= P.FECHA_BAJA AND (CU.FECHA_RENDICION IS NULL OR CU.FECHA_RENDICION > P.FECHA_BAJA) AND CU.ANULADO = 0 AND CU.INACTIVO = 0 UNION ALL SELECT COUNT(*) FROM CREDITOS CR INNER JOIN CUOTAS CU ON CU.COD_CREDITO = CR.COD_CREDITO WHERE CR.COD_PROPUESTA = P.COD_PROPUESTA AND CU.FECHA_VENCIMIENTO <= P.FECHA_BAJA AND (CU.FECHA_RENDICION IS NULL OR CU.FECHA_RENDICION > P.FECHA_BAJA) AND CU.ANULADO = 0) X), CURRENT_TIMESTAMP
  FROM PROPUESTA P WHERE P.COD_PARCELA IS NOT NULL AND P.FECHA_BAJA BETWEEN :V_PERIODO AND :V_HASTA;
  INSERT INTO EST_EVENTOS_PARCELAS (COD_PARCELA, COD_PROPUESTA, PERIODO, FECHA_EVENTO, TIPO_EVENTO, MESES_PENDIENTES, ACTUALIZADO_EN)
  SELECT DISTINCT DI.COD_PARCELA, DI.COD_PROPUESTA, :V_PERIODO, CAST(DI.FECHA_EXHUMACION AS DATE), 'EXHUMACION', NULL, CURRENT_TIMESTAMP FROM DET_INHUMADOS DI WHERE DI.FECHA_EXHUMACION BETWEEN :V_PERIODO AND :V_HASTA;

  SELECT COUNT(*) FROM EST_PARCELAS_CORTE WHERE PERIODO = :V_PERIODO INTO :V_CANT_SNAPSHOTS;
  SELECT COUNT(*) FROM EST_EVENTOS_PARCELAS WHERE PERIODO = :V_PERIODO INTO :V_CANT_EVENTOS;
  UPDATE OR INSERT INTO EST_CARGAS_PARCELAS (PERIODO, FECHA_CORTE, ACTUALIZADO_EN, ESTADO, CANTIDAD_SNAPSHOTS, CANTIDAD_EVENTOS, MENSAJE_ERROR)
    VALUES (:V_PERIODO, :P_FECHA_CORTE, CURRENT_TIMESTAMP, 'EXITOSA', :V_CANT_SNAPSHOTS, :V_CANT_EVENTOS, NULL) MATCHING (PERIODO);

  WHEN ANY DO
  BEGIN
    /* Persiste la auditoria sin publicar los datos parciales de la transaccion principal. */
    IN AUTONOMOUS TRANSACTION DO
    BEGIN
      UPDATE OR INSERT INTO EST_CARGAS_PARCELAS (
        PERIODO, FECHA_CORTE, ACTUALIZADO_EN, ESTADO,
        CANTIDAD_SNAPSHOTS, CANTIDAD_EVENTOS, MENSAJE_ERROR)
      VALUES (:V_PERIODO, :P_FECHA_CORTE, CURRENT_TIMESTAMP, 'FALLIDA',
        0, 0, 'Error durante el refresco de estadisticas.')
      MATCHING (PERIODO);
    END
    EXCEPTION;
  END
END^

CREATE OR ALTER PROCEDURE RESUMEN_ESTADISTICAS_PARCELAS (P_PERIODO DATE, P_PRODUCTO VARCHAR(20))
RETURNS (PERIODO DATE, FECHA_CORTE DATE, ACTUALIZADO_EN TIMESTAMP, CANTIDAD_PARCELAS INTEGER, AL_DIA INTEGER, MOROSAS INTEGER, RECUPERADAS INTEGER)
AS
BEGIN
  FOR SELECT C.PERIODO, C.FECHA_CORTE, C.ACTUALIZADO_EN, COUNT(E.COD_EST_PARCELA_CORTE), COALESCE(SUM(E.ES_AL_DIA),0), COALESCE(SUM(E.ES_MOROSO),0), COALESCE(SUM(E.ES_RECUPERADO),0)
    FROM EST_CARGAS_PARCELAS C LEFT JOIN EST_PARCELAS_CORTE E ON E.PERIODO = C.PERIODO AND (:P_PRODUCTO = 'todos' OR (:P_PRODUCTO = 'dpc' AND E.TIENE_DPC = 1) OR (:P_PRODUCTO = 'flores-siempre' AND E.TIENE_FLORES_SIEMPRE = 1))
    WHERE C.PERIODO = :P_PERIODO AND C.ESTADO = 'EXITOSA' GROUP BY C.PERIODO, C.FECHA_CORTE, C.ACTUALIZADO_EN
    INTO :PERIODO, :FECHA_CORTE, :ACTUALIZADO_EN, :CANTIDAD_PARCELAS, :AL_DIA, :MOROSAS, :RECUPERADAS DO SUSPEND;
END^

CREATE OR ALTER PROCEDURE EVOLUCION_ESTADISTICAS_PARCELAS (P_DESDE DATE, P_HASTA DATE, P_PRODUCTO VARCHAR(20))
RETURNS (PERIODO DATE, FECHA_CORTE DATE, ACTUALIZADO_EN TIMESTAMP, CANTIDAD_PARCELAS INTEGER, AL_DIA INTEGER, MOROSAS INTEGER, RECUPERADAS INTEGER)
AS
BEGIN
  FOR SELECT C.PERIODO, C.FECHA_CORTE, C.ACTUALIZADO_EN, COUNT(E.COD_EST_PARCELA_CORTE), COALESCE(SUM(E.ES_AL_DIA),0), COALESCE(SUM(E.ES_MOROSO),0), COALESCE(SUM(E.ES_RECUPERADO),0)
    FROM EST_CARGAS_PARCELAS C LEFT JOIN EST_PARCELAS_CORTE E ON E.PERIODO = C.PERIODO AND (:P_PRODUCTO = 'todos' OR (:P_PRODUCTO = 'dpc' AND E.TIENE_DPC = 1) OR (:P_PRODUCTO = 'flores-siempre' AND E.TIENE_FLORES_SIEMPRE = 1))
    WHERE C.PERIODO BETWEEN :P_DESDE AND :P_HASTA AND C.ESTADO = 'EXITOSA' GROUP BY C.PERIODO, C.FECHA_CORTE, C.ACTUALIZADO_EN ORDER BY C.PERIODO
    INTO :PERIODO, :FECHA_CORTE, :ACTUALIZADO_EN, :CANTIDAD_PARCELAS, :AL_DIA, :MOROSAS, :RECUPERADAS DO SUSPEND;
END^

CREATE OR ALTER PROCEDURE COBERTURA_ESTADISTICAS_PARCELAS (P_DESDE DATE, P_HASTA DATE)
RETURNS (PERIODO DATE, FECHA_CORTE DATE, ACTUALIZADO_EN TIMESTAMP)
AS
BEGIN
  FOR SELECT PERIODO, FECHA_CORTE, ACTUALIZADO_EN FROM EST_CARGAS_PARCELAS WHERE PERIODO BETWEEN :P_DESDE AND :P_HASTA AND ESTADO = 'EXITOSA' ORDER BY PERIODO INTO :PERIODO, :FECHA_CORTE, :ACTUALIZADO_EN DO SUSPEND;
END^

