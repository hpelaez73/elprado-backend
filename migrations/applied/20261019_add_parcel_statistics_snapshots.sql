CREATE SEQUENCE GEN_EST_PARCELAS_CORTE;
CREATE SEQUENCE GEN_EST_EVENTOS_PARCELAS;
CREATE SEQUENCE GEN_EST_CARGAS_PARCELAS;
CREATE EXCEPTION EXC_ESTADISTICAS_PARCELAS 'Parámetros inválidos para la carga de estadísticas.';

CREATE TABLE EST_PARCELAS_CORTE (
  COD_EST_PARCELA_CORTE INTEGER NOT NULL,
  COD_PARCELA INTEGER NOT NULL,
  COD_PROPUESTA INTEGER NOT NULL,
  PERIODO DATE NOT NULL,
  FECHA_CORTE DATE NOT NULL,
  ES_ACTIVO SMALLINT NOT NULL,
  ES_AL_DIA SMALLINT NOT NULL,
  ES_MOROSO SMALLINT NOT NULL,
  ES_RECUPERADO SMALLINT NOT NULL,
  ES_DEUDOR_RECIENTE SMALLINT NOT NULL,
  MESES_PENDIENTES INTEGER NOT NULL,
  TIENE_DPC SMALLINT NOT NULL,
  TIENE_FLORES_SIEMPRE SMALLINT NOT NULL,
  ACTUALIZADO_EN TIMESTAMP NOT NULL
);
ALTER TABLE EST_PARCELAS_CORTE ADD CONSTRAINT PK_EST_PARCELAS_CORTE
  PRIMARY KEY (COD_EST_PARCELA_CORTE);
ALTER TABLE EST_PARCELAS_CORTE ADD CONSTRAINT UQ_EST_PARCELAS_CORTE_PER_PARC
  UNIQUE (PERIODO, COD_PARCELA);
ALTER TABLE EST_PARCELAS_CORTE ADD CONSTRAINT FK_EST_CORTE_PARCELA
  FOREIGN KEY (COD_PARCELA) REFERENCES PARCELA (COD_PARCELA);
ALTER TABLE EST_PARCELAS_CORTE ADD CONSTRAINT FK_EST_CORTE_PROPUESTA
  FOREIGN KEY (COD_PROPUESTA) REFERENCES PROPUESTA (COD_PROPUESTA);
CREATE INDEX IX_EST_CORTE_PERIODO_PRODUCTO ON EST_PARCELAS_CORTE
  (PERIODO, TIENE_FLORES_SIEMPRE);

CREATE TABLE EST_EVENTOS_PARCELAS (
  COD_EST_EVENTO_PARCELA INTEGER NOT NULL,
  COD_PARCELA INTEGER NOT NULL,
  COD_PROPUESTA INTEGER NOT NULL,
  PERIODO DATE NOT NULL,
  FECHA_EVENTO DATE NOT NULL,
  TIPO_EVENTO VARCHAR(12) NOT NULL,
  MESES_PENDIENTES INTEGER,
  ACTUALIZADO_EN TIMESTAMP NOT NULL
);
ALTER TABLE EST_EVENTOS_PARCELAS ADD CONSTRAINT PK_EST_EVENTOS_PARCELAS
  PRIMARY KEY (COD_EST_EVENTO_PARCELA);
ALTER TABLE EST_EVENTOS_PARCELAS ADD CONSTRAINT UQ_EST_EVENTOS_PROP_TIPO_FECHA
  UNIQUE (COD_PROPUESTA, TIPO_EVENTO, FECHA_EVENTO);
ALTER TABLE EST_EVENTOS_PARCELAS ADD CONSTRAINT CK_EST_EVENTOS_TIPO
  CHECK (TIPO_EVENTO IN ('ALTA', 'BAJA', 'EXHUMACION'));
ALTER TABLE EST_EVENTOS_PARCELAS ADD CONSTRAINT FK_EST_EVENTOS_PARCELA
  FOREIGN KEY (COD_PARCELA) REFERENCES PARCELA (COD_PARCELA);
ALTER TABLE EST_EVENTOS_PARCELAS ADD CONSTRAINT FK_EST_EVENTOS_PROPUESTA
  FOREIGN KEY (COD_PROPUESTA) REFERENCES PROPUESTA (COD_PROPUESTA);
CREATE INDEX IX_EST_EVENTOS_PERIODO_TIPO ON EST_EVENTOS_PARCELAS
  (PERIODO, TIPO_EVENTO);

CREATE TABLE EST_CARGAS_PARCELAS (
  COD_EST_CARGA_PARCELA INTEGER NOT NULL,
  PERIODO DATE NOT NULL,
  FECHA_CORTE DATE NOT NULL,
  ACTUALIZADO_EN TIMESTAMP NOT NULL,
  ESTADO VARCHAR(12) NOT NULL,
  CANTIDAD_SNAPSHOTS INTEGER NOT NULL,
  CANTIDAD_EVENTOS INTEGER NOT NULL,
  MENSAJE_ERROR VARCHAR(500)
);
ALTER TABLE EST_CARGAS_PARCELAS ADD CONSTRAINT PK_EST_CARGAS_PARCELAS
  PRIMARY KEY (COD_EST_CARGA_PARCELA);
ALTER TABLE EST_CARGAS_PARCELAS ADD CONSTRAINT UQ_EST_CARGAS_PERIODO
  UNIQUE (PERIODO);
ALTER TABLE EST_CARGAS_PARCELAS ADD CONSTRAINT CK_EST_CARGAS_ESTADO
  CHECK (ESTADO IN ('EXITOSA', 'FALLIDA'));
CREATE INDEX IX_EST_CARGAS_PERIODO ON EST_CARGAS_PARCELAS (PERIODO);

