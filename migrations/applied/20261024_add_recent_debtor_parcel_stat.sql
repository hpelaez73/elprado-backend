/*
  Expone el indicador existente de deudor reciente en los procedimientos de estadisticas.
*/

SET TERM ^;

CREATE OR ALTER PROCEDURE RESUMEN_ESTADISTICAS_PARCELAS (P_PERIODO DATE, P_PRODUCTO VARCHAR(20))
RETURNS (PERIODO DATE, FECHA_CORTE DATE, ACTUALIZADO_EN TIMESTAMP, CANTIDAD_PARCELAS INTEGER, AL_DIA INTEGER, MOROSAS INTEGER, RECUPERADAS INTEGER, DEUDORES_RECIENTES INTEGER)
AS
BEGIN
  FOR
    SELECT C.PERIODO, C.FECHA_CORTE, C.ACTUALIZADO_EN, COUNT(E.COD_EST_PARCELA_CORTE), COALESCE(SUM(E.ES_AL_DIA),0), COALESCE(SUM(E.ES_MOROSO),0), COALESCE(SUM(E.ES_RECUPERADO),0), COALESCE(SUM(E.ES_DEUDOR_RECIENTE),0)
    FROM EST_CARGAS_PARCELAS C
    LEFT JOIN EST_PARCELAS_CORTE E ON E.PERIODO = C.PERIODO AND (:P_PRODUCTO = 'todos' OR (:P_PRODUCTO = 'dpc' AND E.TIENE_DPC = 1) OR (:P_PRODUCTO = 'flores-siempre' AND E.TIENE_FLORES_SIEMPRE = 1))
    WHERE C.PERIODO = :P_PERIODO AND C.ESTADO = 'EXITOSA'
    GROUP BY C.PERIODO, C.FECHA_CORTE, C.ACTUALIZADO_EN
    INTO :PERIODO, :FECHA_CORTE, :ACTUALIZADO_EN, :CANTIDAD_PARCELAS, :AL_DIA, :MOROSAS, :RECUPERADAS, :DEUDORES_RECIENTES
  DO
    SUSPEND;
END^

CREATE OR ALTER PROCEDURE EVOLUCION_ESTADISTICAS_PARCELAS (P_DESDE DATE, P_HASTA DATE, P_PRODUCTO VARCHAR(20))
RETURNS (PERIODO DATE, FECHA_CORTE DATE, ACTUALIZADO_EN TIMESTAMP, CANTIDAD_PARCELAS INTEGER, AL_DIA INTEGER, MOROSAS INTEGER, RECUPERADAS INTEGER, DEUDORES_RECIENTES INTEGER)
AS
BEGIN
  FOR
    SELECT C.PERIODO, C.FECHA_CORTE, C.ACTUALIZADO_EN, COUNT(E.COD_EST_PARCELA_CORTE), COALESCE(SUM(E.ES_AL_DIA),0), COALESCE(SUM(E.ES_MOROSO),0), COALESCE(SUM(E.ES_RECUPERADO),0), COALESCE(SUM(E.ES_DEUDOR_RECIENTE),0)
    FROM EST_CARGAS_PARCELAS C
    LEFT JOIN EST_PARCELAS_CORTE E ON E.PERIODO = C.PERIODO AND (:P_PRODUCTO = 'todos' OR (:P_PRODUCTO = 'dpc' AND E.TIENE_DPC = 1) OR (:P_PRODUCTO = 'flores-siempre' AND E.TIENE_FLORES_SIEMPRE = 1))
    WHERE C.PERIODO BETWEEN :P_DESDE AND :P_HASTA AND C.ESTADO = 'EXITOSA'
    GROUP BY C.PERIODO, C.FECHA_CORTE, C.ACTUALIZADO_EN
    ORDER BY C.PERIODO
    INTO :PERIODO, :FECHA_CORTE, :ACTUALIZADO_EN, :CANTIDAD_PARCELAS, :AL_DIA, :MOROSAS, :RECUPERADAS, :DEUDORES_RECIENTES
  DO
    SUSPEND;
END^

SET TERM ;^
