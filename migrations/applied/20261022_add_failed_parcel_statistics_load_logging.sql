/*
  Conserva la implementacion desplegada de REFRESCAR_ESTADISTICAS_PARCELAS y
  agrega auditoria de fallos en una transaccion autonoma.
  Requiere Firebird 3.0 o superior.
*/

SET TERM ^;

EXECUTE BLOCK
AS
DECLARE VARIABLE V_SOURCE BLOB SUB_TYPE TEXT;
DECLARE VARIABLE V_SQL BLOB SUB_TYPE TEXT;
BEGIN
  SELECT RDB$PROCEDURE_SOURCE
    FROM RDB$PROCEDURES
    WHERE RDB$PROCEDURE_NAME = 'REFRESCAR_ESTADISTICAS_PARCELAS'
    INTO :V_SOURCE;

  IF (V_SOURCE IS NULL) THEN
    EXCEPTION EXC_ESTADISTICAS_PARCELAS;

  V_SOURCE = TRIM(TRAILING FROM V_SOURCE);
  V_SOURCE = SUBSTRING(V_SOURCE FROM 1 FOR CHAR_LENGTH(V_SOURCE) - 3) ||
    '  WHEN ANY DO
       BEGIN
         IN AUTONOMOUS TRANSACTION DO
         BEGIN
           UPDATE OR INSERT INTO EST_CARGAS_PARCELAS (
             PERIODO, FECHA_CORTE, ACTUALIZADO_EN, ESTADO,
             CANTIDAD_SNAPSHOTS, CANTIDAD_EVENTOS, MENSAJE_ERROR)
           VALUES (:V_PERIODO, :P_FECHA_CORTE, CURRENT_TIMESTAMP, ''FALLIDA'',
             0, 0, ''Error durante el refresco de estadisticas.'')
           MATCHING (PERIODO);
         END
         EXCEPTION;
       END
     END';

  V_SQL = 'ALTER PROCEDURE REFRESCAR_ESTADISTICAS_PARCELAS (
    P_PERIODO DATE,
    P_FECHA_CORTE DATE,
    P_RECONSTRUIR SMALLINT)
  AS ' || V_SOURCE;
  EXECUTE STATEMENT V_SQL;
END^

SET TERM ;^
